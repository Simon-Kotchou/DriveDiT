bv = importlib.util.module_from_spec(_bv_spec)
_bv_spec.loader.exec_module(bv)


def listing(root):
    out = set()
    for dirpath, _, files in os.walk(root):
        for name in files:
            out.add(os.path.relpath(os.path.join(dirpath, name), root).replace(os.sep, "/"))
    return out


