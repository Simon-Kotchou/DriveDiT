    def test_refuses_denied_sources_that_exist(self):
        # As after a restore from tag archive/dc1-rust: a scratch repo with a copy of the tool holds every denied
        # source as a real file. Each is refused for its policy reason and nothing is written. A file no rule denies
        # deploys from the same scratch repo, so the refusals come from the deny rules, not from the setup.
        repo = os.path.join(self.tmp, "repo")
        tool = os.path.join(repo, "tools", "deploy_addon.py")
        allowed = "src/enfusion/datacapture/DC_SelfTestAllowed.c"
        os.makedirs(os.path.dirname(tool))
        shutil.copyfile(TOOL, tool)
        for rel in ["addons/DataCapture/addon.gproj", allowed] + [src for _, src, _ in DENIED_SOURCES]:
            path = os.path.join(repo, *rel.split("/"))
            os.makedirs(os.path.dirname(path), exist_ok=True)
            if rel.endswith(".gproj") and rel.startswith("addons/"):
                shutil.copyfile(os.path.join(REPO, *rel.split("/")), path)
            else:
                with open(path, "w", encoding="ascii") as f:
                    f.write("// deploy self-test stand-in for %s\n" % rel)

        def run(line):
            manifest = self.write_manifest(["addon addons/DataCapture/addon.gproj", line])
            cmd = [sys.executable, "-I", "-B", tool, "--target", self.target, "--allow-root", self.tmp,
                   "--manifest", manifest]
            p = subprocess.run(cmd, cwd=self.tmp, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
            return p.returncode, p.stdout.decode() + p.stderr.decode()

        for kind, src, reason in DENIED_SOURCES:
            self.assertTrue(os.path.isfile(os.path.join(repo, *src.split("/"))), src)
            rc, out = run("%s %s" % (kind, src))
            self.assertEqual(rc, 2, "%s: %s" % (src, out))
            self.assertIn(reason, out, src)
            self.assertNotIn("does not exist in the repo", out, src)
            self.assertFalse(os.path.exists(self.target), "%s: refusal still wrote the target" % src)
        rc, out = run("script " + allowed)
        self.assertEqual(rc, 0, out)
        self.assertTrue(os.path.isfile(os.path.join(self.target, SCRIPT_DST, "DC_SelfTestAllowed.c")), out)

    def test_refuses_symlinked_directories_inside_the_target(self):
        self.assertEqual(self.run_tool()[0], 0)
        outside = os.path.join(self.tmp, "outside")
        os.makedirs(outside)
        # A Scripts folder that points elsewhere (e.g. a junction into an old C: addon) must not receive the scripts.
        shutil.rmtree(os.path.join(self.target, "Scripts"))
        os.symlink(outside, os.path.join(self.target, "Scripts"))
        rc, out = self.run_tool()
        self.assertEqual(rc, 2, out)
        self.assertIn("symlink or junction", out)
        self.assertEqual(os.listdir(outside), [], "a deploy wrote through a symlinked directory")
        os.remove(os.path.join(self.target, "Scripts"))

        # A redirected backup folder must not receive --force backups.
        self.assertEqual(self.run_tool()[0], 0)
        layer = os.path.join(self.target, *WORLD_LAYER.split("/"))
        with open(layer, "ab") as f:
            f.write(b"// saved by Workbench\n")
        edited = sha(layer)
